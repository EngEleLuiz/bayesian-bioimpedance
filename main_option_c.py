"""
main_option_c.py
================
Option C pipeline: honest validation using Gabriel's full dielectric
model (4-Cole-Cole) with a band-limited (beta sub-band) fit.

BEFORE RUNNING -- MANDATORY STEP
====================================
The full delta_eps_n / tau_n / alpha_n parameters for each tissue in
`src/gabriel_4cc_model.py` (MUSCLE_4CC_PARTIAL) are marked as
UNVERIFIED. Before using this pipeline for the final paper:

  1. Go to: https://www.fcc.gov/general/body-tissue-dielectric-parameters
  2. Select the "Muscle" tissue
  3. For each frequency in your grid (e.g. 100 Hz, 215 Hz, 464 Hz, ...,
     1 MHz -- 30 log-spaced points), note eps' (Permittivity) and
     sigma (Conductivity, S/m)
  4. Fill in `fcc_lookup_data.csv` (generated by `--generate-template`)
     with the real looked-up values
  5. Run the pipeline with `--csv-fcc fcc_lookup_data.csv`

This removes any risk of parameter transcription error and makes the
validation 100% traceable to the official source.

Usage:
    # Generate a CSV template to fill in using the official calculator
    python main_option_c.py --generate-template

    # Run with real data looked up on the FCC site
    python main_option_c.py --csv-fcc fcc_lookup_data.csv

    # Demo mode (uses UNVERIFIED parameters -- code testing only)
    python main_option_c.py --demo --fast
"""

