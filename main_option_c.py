def generate_fcc_csv_template(filepath="fcc_lookup_data.csv",
                               n_freq=30, f_min=100.0, f_max=1e6):
    """Generate a CSV template with the frequency grid to look up on the official FCC/IFAC-CNR calculator."""
    f = frequency_grid(f_min, f_max, n_freq)
    with open(filepath, "w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["freq_hz", "eps_prime", "sigma_S_per_m", "source"])
        for fi in f:
            writer.writerow([f"{fi:.4f}", "", "", ""])

    print(f"\nTemplate saved to: {filepath}")
    print(f"\n{'='*70}")
    print("  NEXT STEP (manual, ~5 minutes):")
    print(f"{'='*70}")
    print("  1. Go to: https://www.fcc.gov/general/body-tissue-dielectric-parameters")
    print("  2. Select the tissue (e.g. Muscle)")
    print(f"  3. For each of the {n_freq} frequencies in the CSV, look up")
    print("     eps' (permittivity) and sigma (conductivity, S/m)")
    print("  4. Fill in the 'eps_prime' and 'sigma_S_per_m' columns")
    print(f"  5. Run: python main_option_c.py --csv-fcc {filepath}")
    print(f"{'='*70}\n")
    return filepath


def load_fcc_csv(filepath):
    """Load a CSV filled with values looked up on the FCC/IFAC-CNR calculator."""
    freqs, eps_vals, sigma_vals = [], [], []
    with open(filepath, "r") as fh:
        for row in csv.DictReader(fh):
            try:
                freqs.append(float(row["freq_hz"]))
                eps_vals.append(float(row["eps_prime"]))
                sigma_vals.append(float(row["sigma_S_per_m"]))
            except (ValueError, KeyError):
                continue

    if len(freqs) < 5:
        raise ValueError(
            f"CSV '{filepath}' has only {len(freqs)} filled rows. "
            "Fill in the eps_prime and sigma_S_per_m columns with values "
            "looked up on the official calculator before running."
        )

    idx = np.argsort(freqs)
    return np.array(freqs)[idx], np.array(eps_vals)[idx], np.array(sigma_vals)[idx]


