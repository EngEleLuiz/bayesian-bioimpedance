def plot_full_spectrum_with_band(f_full, Z_full, f_band, Z_band, band_range, save_path=None):
    """Show the full spectrum (Gabriel model) with the beta sub-band highlighted -- an honest view of 'everything' vs. 'identifiable'."""
    fig, (ax_ny, ax_mod, ax_ph) = plt.subplots(1, 3, figsize=(14, 4))

    ax_ny.plot(Z_full.real, -Z_full.imag, '--', color="gray", alpha=0.6,
               label="Full spectrum (Gabriel 4-CC)")
    ax_ny.plot(Z_band.real, -Z_band.imag, 'o-', color="#1f77b4", ms=4,
               label=f"Beta sub-band [{band_range[0]:.0f}, {band_range[1]:.0f}] Hz")
    ax_ny.set_xlabel(r"$\Re[Z]$ [Ohm]"); ax_ny.set_ylabel(r"$-\Im[Z]$ [Ohm]")
    ax_ny.set_title("(a) Nyquist"); ax_ny.legend(fontsize=8)

    ax_mod.loglog(f_full, np.abs(Z_full), '--', color="gray", alpha=0.6, label="Full")
    ax_mod.loglog(f_band, np.abs(Z_band), 'o-', color="#1f77b4", ms=4, label="Beta sub-band")
    ax_mod.axvspan(*band_range, alpha=0.1, color="#1f77b4")
    ax_mod.set_xlabel("Frequency [Hz]"); ax_mod.set_ylabel(r"$|Z|$ [Ohm]")
    ax_mod.set_title("(b) Magnitude"); ax_mod.legend(fontsize=8)

    ax_ph.semilogx(f_full, np.angle(Z_full, deg=True), '--', color="gray", alpha=0.6)
    ax_ph.semilogx(f_band, np.angle(Z_band, deg=True), 'o-', color="#1f77b4", ms=4)
    ax_ph.axvspan(*band_range, alpha=0.1, color="#1f77b4")
    ax_ph.set_xlabel("Frequency [Hz]"); ax_ph.set_ylabel("Phase [deg]")
    ax_ph.set_title("(c) Phase")

    fig.suptitle("Full Dielectric Spectrum (Gabriel 4-CC) vs. Identifiable Sub-band",
                 fontsize=12, fontweight="bold")
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, bbox_inches="tight", dpi=150)
        print(f"  Figure saved: {save_path}")
    plt.show()
    return fig


def plot_subband_fit_result(result, save_path=None):
    """Show the single-dispersion Cole-Cole fit within the beta sub-band."""
    from src.analysis import samples_to_physical

    f_band, z_band = result["f_band"], result["Z_band"]
    phys = samples_to_physical(result["mcmc_samples"])
    r_med, r0_med = np.median(phys["R_inf"]), np.median(phys["R0"])
    tau_med, alpha_med = np.median(phys["tau"]), np.median(phys["alpha"])
    z_fit = cole_cole_impedance(f_band, r_med, r0_med, tau_med, alpha_med)

    fig, (ax_ny, ax_mod, ax_ph) = plt.subplots(1, 3, figsize=(14, 4))

    ax_ny.scatter(z_band.real, -z_band.imag, color="gray", s=25,
                  label="Data (beta sub-band)", zorder=5)
    ax_ny.plot(z_fit.real, -z_fit.imag, color="#1f77b4", lw=2,
               label="Cole-Cole fit (1 dispersion)")
    ax_ny.set_xlabel(r"$\Re[Z]$ [Ohm]"); ax_ny.set_ylabel(r"$-\Im[Z]$ [Ohm]")
    ax_ny.set_title(f"(a) Nyquist -- R2={result['r_squared_subband']:.4f}")
    ax_ny.legend(fontsize=8); ax_ny.set_aspect("equal", adjustable="datalim")

    ax_mod.semilogx(f_band, np.abs(z_band), 'o', color="gray", ms=5)
    ax_mod.semilogx(f_band, np.abs(z_fit), color="#1f77b4", lw=2)
    ax_mod.set_xlabel("Frequency [Hz]"); ax_mod.set_ylabel(r"$|Z|$ [Ohm]")
    ax_mod.set_title("(b) Magnitude")

    ax_ph.semilogx(f_band, np.angle(z_band, deg=True), 'o', color="gray", ms=5)
    ax_ph.semilogx(f_band, np.angle(z_fit, deg=True), color="#1f77b4", lw=2)
    ax_ph.set_xlabel("Frequency [Hz]"); ax_ph.set_ylabel("Phase [deg]")
    ax_ph.set_title("(c) Phase")

    cov_pct = result["coverage_fraction"] * 100
    fig.suptitle(f"Cole-Cole Fit -- Honest Beta Sub-band ({cov_pct:.0f}% of the full spectrum)",
                 fontsize=12, fontweight="bold")
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, bbox_inches="tight", dpi=150)
        print(f"  Figure saved: {save_path}")
    plt.show()
    return fig


