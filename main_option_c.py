def parse_args():
    p = argparse.ArgumentParser(description="Option C -- Honest band-limited validation")
    p.add_argument("--generate-template", dest="generate_template", action="store_true",
                   help="[Legacy] Generate a CSV template for a manual FCC lookup")
    p.add_argument("--generate-template-itis", dest="generate_template_itis", action="store_true",
                   help="[RECOMMENDED] Generate a CSV template to fill in from the "
                        "official IT'IS Foundation spreadsheet (14 params/tissue)")
    p.add_argument("--csv-fcc", type=str, default=None,
                   help="[Legacy] CSV with (freq, eps', sigma) looked up on the FCC site")
    p.add_argument("--csv-itis", type=str, default=None,
                   help="[RECOMMENDED] CSV with the 14 4-CC parameters read from the "
                        "official IT'IS Foundation spreadsheet")
    p.add_argument("--r-inf-calib", type=float, default=50.0,
                   help="Reference resistance [Ohm] to calibrate the unknown measurement "
                        "geometry (default: 50 Ohm, typical for soft tissue)")
    p.add_argument("--demo", action="store_true",
                   help="Demo mode (UNVERIFIED parameters, code testing only)")
    p.add_argument("--fast", action="store_true")
    p.add_argument("--snr", type=float, default=30.0)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--output", type=str, default="results_option_c")
    return p.parse_args()


def main():
    args = parse_args()

    if args.generate_template:
        generate_fcc_csv_template()
        return
    if args.generate_template_itis:
        generate_itis_csv_template()
        return

    n_samples = 1500 if args.fast else 4000
    n_warmup = 750 if args.fast else 2000

    if args.csv_itis:
        run_itis_csv_mode(args.csv_itis, n_samples, n_warmup, args.seed,
                           args.output, args.snr, args.r_inf_calib)
    elif args.csv_fcc:
        run_fcc_csv_mode(args.csv_fcc, n_samples, n_warmup, args.seed,
                          args.output, args.snr)
    elif args.demo:
        run_demo_mode(n_samples, n_warmup, args.seed, args.output)
    else:
        print("Please specify an option:")
        print("  --generate-template-itis  (RECOMMENDED -- one-time download)")
        print("  --csv-itis <file>         (RECOMMENDED -- run with real data)")
        print("  --generate-template / --csv-fcc <file>  (legacy, manual)")
        print("  --demo                    (code testing only)")
        print("Use --help for more information")


if __name__ == "__main__":
    main()
