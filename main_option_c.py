def run_demo_mode(n_samples, n_warmup, seed, output_dir):
    """Demo mode: uses MUSCLE_4CC_PARTIAL (UNVERIFIED parameters) only to check that the code runs. Do NOT use for the paper."""
    print("\n" + "WARNING " * 8)
    print("  DEMO MODE -- UNVERIFIED parameters")
    print("  Do NOT use these results in the final paper.")
    print("  Run with --csv-fcc or --csv-itis after consulting an official source.")
    print("WARNING " * 8 + "\n")

    os.makedirs(output_dir, exist_ok=True)
    f_full = frequency_grid(10.0, 1e8, 200)   # wide band to see all 4 dispersions
    z_full = impedance_from_4cc(f_full, MUSCLE_4CC_PARTIAL)

    f_grid = frequency_grid(100.0, 1e6, 30)   # our experimental grid
    z_grid = impedance_from_4cc(f_grid, MUSCLE_4CC_PARTIAL)

    f_band, z_band_clean = select_beta_band(f_grid, z_grid, 1e3, 1e6)
    plot_full_spectrum_with_band(f_full, z_full, f_band, z_band_clean, (1e3, 1e6),
                                  save_path=os.path.join(output_dir, "demo_full_spectrum_vs_band.png"))

    result = fit_single_cole_cole_subband(f_grid, z_grid, f_low=1e3, f_high=1e6,
                                           snr_db=30.0, n_samples=n_samples,
                                           n_warmup=n_warmup, seed=seed)

    print(f"\n  R2 (sub-band): {result['r_squared_subband']:.4f}")
    print(f"  Coverage: {result['coverage_fraction']*100:.0f}% of the full spectrum")
    p = result["params_median"]
    print(f"  R_inf={p['R_inf']:.2f} Ohm  R0={p['R0']:.2f} Ohm  "
          f"tau={p['tau']*1e6:.2f} us  alpha={p['alpha']:.3f}")

    plot_subband_fit_result(result, save_path=os.path.join(output_dir, "demo_subband_fit.png"))
    return result


def run_itis_csv_mode(csv_path, n_samples, n_warmup, seed, output_dir,
                       snr_db=30.0, r_inf_calib=50.0):
    """Pipeline using raw Gabriel (4-CC) parameters read from the official IT'IS Foundation spreadsheet -- the RECOMMENDED validation route (one file, all tissues, no point-by-point lookups)."""
    print("\n" + "=" * 60)
    print("  OPTION C (v2) -- Validation with the IT'IS Foundation database")
    print("  Primary source: Gabriel et al. (1996)")
    print("=" * 60)

    os.makedirs(output_dir, exist_ok=True)
    tissues = load_itis_csv(csv_path)

    results = {}
    for name, params in tissues.items():
        print(f"\n  -- Tissue: {name} --")

        if not validate_physical_parameters(params):
            print(f"  Skipping '{name}' -- fix the parameters and re-run.")
            continue

        f_grid = frequency_grid(100.0, 1e6, 30)
        z_grid = impedance_from_4cc_calibrated(f_grid, params, target_r_inf=r_inf_calib, f_ref=1e6)
        f_band, z_band_clean = select_beta_band(f_grid, z_grid, 1e3, 1e6)
        print(f"  Beta sub-band: {len(f_band)}/{len(f_grid)} points "
              f"({len(f_band)/len(f_grid)*100:.0f}%)")

        plot_full_spectrum_with_band(f_grid, z_grid, f_band, z_band_clean, (1e3, 1e6),
                                      save_path=os.path.join(output_dir, f"{name}_full_spectrum_vs_band.png"))

        result = fit_single_cole_cole_subband(f_grid, z_grid, f_low=1e3, f_high=1e6,
                                               snr_db=snr_db, n_samples=n_samples,
                                               n_warmup=n_warmup, seed=seed)

        print(f"  R2 (sub-band): {result['r_squared_subband']:.4f}")
        p = result["params_median"]
        print(f"  R_inf={p['R_inf']:.2f} Ohm  R0={p['R0']:.2f} Ohm  "
              f"tau={p['tau']*1e6:.2f} us  alpha={p['alpha']:.3f}")

        plot_subband_fit_result(result, save_path=os.path.join(output_dir, f"{name}_subband_fit.png"))
        results[name] = result

    print(f"\n  Results saved to: {os.path.abspath(output_dir)}/")
    return results


